/**
 * #146 (R3-05): текст, когда список групп не обновился. Обещаем сохранённое расписание только если оно есть
 * для текущей группы. Иначе баннер противоречил экрану («Выберите учебную группу» / «Войдите в аккаунт…»).
 */
export function catalogFailureNotice(hasCatalog: boolean, hasCachedSchedule: boolean): string {
  if (!hasCatalog) return "Список групп недоступен, сохранённой копии списка нет.";
  return hasCachedSchedule
    ? "Список групп не обновился. Сохранённое расписание остаётся доступным."
    : "Список групп не обновился. Проверьте подключение к интернету.";
}
